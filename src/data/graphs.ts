import type { Difficulty, Graph } from '../engine/graph';

interface Spec {
  id: string;
  name: string;
  description: string;
  note?: string;
  difficulty: Difficulty;
  directed: boolean;
  weighted: boolean;
  start: string;
  goal: string;
  dlsLimit: number;
  /** [id, x, y, h] */
  nodes: [string, number, number, number?][];
  /** [from, to, weight] (weight is ignored for unweighted graphs) */
  edges: [string, string, number?][];
}

function build(spec: Spec): Graph {
  return {
    id: spec.id,
    name: spec.name,
    description: spec.description,
    note: spec.note,
    difficulty: spec.difficulty,
    directed: spec.directed,
    weighted: spec.weighted,
    start: spec.start,
    goal: spec.goal,
    dlsLimit: spec.dlsLimit,
    nodes: spec.nodes.map(([id, x, y, h]) => (h === undefined ? { id, x, y } : { id, x, y, h })),
    edges: spec.edges.map(([from, to, w]) => ({ from, to, w: w ?? 1 })),
  };
}

